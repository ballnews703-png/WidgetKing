// The script can update ITSELF: fetch the deployed designer page, extract
// the newer renderer, splice this script's own designs back in, and rewrite
// this file in place. Runs only inside the Scriptable app, never in widgets.
async function checkForUpdates(manual, silent) {
  function say(title, message) {
    // Widgets can't present alerts — silent mode updates the file and says nothing.
    if (silent) return Promise.resolve();
    const a = new Alert();
    a.title = title;
    a.message = message;
    a.addAction("OK");
    return a.presentAlert();
  }
  if (!WK_PAGE_URL || WK_PAGE_URL.indexOf("http") !== 0) {
    if (manual) await say("Updates unavailable", "This copy wasn't exported from the hosted designer.");
    return;
  }
  const prefs = loadPrefs();
  const now = Date.now();
  if (!manual && now - (Number(prefs.lastUpdateCheck) || 0) < 20 * 60 * 60 * 1000) return;
  prefs.lastUpdateCheck = now;
  savePrefs(prefs);
  try {
    const html = await new Request(WK_PAGE_URL + "?wkupd=" + now).loadString();
    const startTag = 'id="scriptableTemplate">';
    const i = html.indexOf(startTag);
    const j = i < 0 ? -1 : html.indexOf("<" + "/script>", i);
    if (i < 0 || j < 0) { if (manual) await say("Update check failed", "Couldn't read the designer page."); return; }
    const tpl = html.substring(i + startTag.length, j).trim();
    const m = tpl.match(/WK_VERSION = (\d+)/);
    if (!m || Number(m[1]) <= WK_VERSION) {
      if (manual) await say("Up to date ✓", "You're on v" + WK_VERSION + " — the latest.");
      return;
    }
    let fm = FileManager.local();
    if (!fm.fileExists(module.filename)) {
      try {
        const icloud = FileManager.iCloud();
        if (icloud.fileExists(module.filename)) fm = icloud;
      } catch (e) {}
    }
    if (!fm.fileExists(module.filename)) {
      if (manual) await say("Update failed", "Couldn't locate this script's file.");
      return;
    }
    // Placeholder tokens are built by concatenation so this code never
    // contains them literally (the designer requires exactly one of each).
    const dTok = '"__DESIGNS' + '__"';
    const uTok = '"__PAGE_URL' + '__"';
    let next = tpl.replace(dTok, JSON.stringify(DESIGNS, null, 2));
    next = next.replace(uTok, JSON.stringify(WK_PAGE_URL));
    fm.writeString(module.filename, next);
    await say("Updated to v" + m[1] + " ✓", "Your designs are kept exactly as they were. Close and reopen the script to finish.");
  } catch (e) {
    if (manual) await say("Update check failed", String(e && e.message || e));
  }
}

