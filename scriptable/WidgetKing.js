function vglyphFor(label) {
  const lower = String(label || "").toLowerCase();
  for (const pair of VGLYPH_FOR) {
    if (lower.indexOf(pair[0]) >= 0) return VGLYPHS[pair[1]];
  }
  return null;
}
function vglyphPoints(stroke) {
  const first = stroke[0];
  if (Array.isArray(first) && (first[0] === "c" || first[0] === "a")) {
    const cx = first[1], cy = first[2], r = first[3];
    const a0 = first[0] === "c" ? 0 : first[4];
    const a1 = first[0] === "c" ? Math.PI * 2 : first[5];
    const n = Math.max(10, Math.round(20 * Math.abs(a1 - a0) / Math.PI));
    const pts = [];
    for (let i = 0; i <= n; i++) {
      const a = a0 + (a1 - a0) * (i / n);
      pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
    }
    return pts;
  }
  return stroke;
}
function vlerpHex(a, b, t) {
  const pa = hexToRgb(a), pb = hexToRgb(b);
  return rgbToHex([0, 1, 2].map(function (i) { return pa[i] + (pb[i] - pa[i]) * t; }));
}
function strokeVGlyph(ctx, strokes, cx, cy, sizePx, lineW, colorA, colorB, alpha) {
  ctx.setLineWidth(lineW);
  const op = typeof alpha === "number" ? alpha : 1;
  for (const stroke of strokes) {
    const pts = vglyphPoints(stroke);
    for (let i = 0; i < pts.length - 1; i++) {
      const t = (pts[i][0] + pts[i][1] + pts[i + 1][0] + pts[i + 1][1]) / 4;
      ctx.setStrokeColor(new Color(colorB ? vlerpHex(colorA, colorB, Math.min(1, Math.max(0, t))) : colorA, op));
      const p = new Path();
      p.move(new Point(cx + (pts[i][0] - 0.5) * sizePx, cy + (pts[i][1] - 0.5) * sizePx));
      p.addLine(new Point(cx + (pts[i + 1][0] - 0.5) * sizePx, cy + (pts[i + 1][1] - 0.5) * sizePx));
      ctx.addPath(p);
      ctx.strokePath();
    }
  }
}
// Themed tiles use clean letter monograms; only the Basic theme (and the
// untinted fallback) keeps the app's emoji.
function iconGlyph(app, themeName) {
  const letterOnly = themeName && themeName !== "basic";
  if (!letterOnly && app.emoji && app.emoji !== "📱" && app.emoji !== "🌐" && app.emoji !== "📲") return app.emoji;
  return (app.label || "A").trim().charAt(0).toUpperCase();
}
function themedIconTile(app, themeName, index, pt) {
  const theme = ICON_THEMES[themeName];
  const S = Math.round(pt * 3);
  const ctx = new DrawContext();
  ctx.size = new Size(S, S);
  ctx.opaque = false;
  ctx.respectScreenScale = false;
  const r = Math.round(S * (theme.radius || 0.24));
  const rect = new Rect(0, 0, S, S);
  const bg = theme.colors[index % theme.colors.length];
  const path = new Path();
  path.addRoundedRect(rect, r, r);
  ctx.addPath(path);
  if (theme.frost) { ctx.setFillColor(new Color("#FFFFFF", 0.25)); }
  else { ctx.setFillColor(new Color(bg)); }
  ctx.fillPath();
  if (theme.duo) {
    // Soft accent orb toward the lower-right — stays inside the tile so it
    // never pokes past the rounded corners (DrawContext can't clip).
    const b = theme.duo[index % theme.duo.length];
    ctx.setFillColor(new Color(b, 0.8));
    ctx.fillEllipse(new Rect(S * 0.34, S * 0.34, S * 0.62, S * 0.62));
  }
  const glyphColor = theme.glyphCycle ? theme.glyphCycle[index % theme.glyphCycle.length] : theme.glyph;
  if (theme.line || theme.lineCycle || theme.frost) {
    const inset = Math.max(2, Math.round(S * 0.035));
    const inner = new Path();
    inner.addRoundedRect(new Rect(inset, inset, S - 2 * inset, S - 2 * inset), r - inset, r - inset);
    ctx.addPath(inner);
    const strokeColor = theme.lineCycle ? glyphColor : (theme.frost ? "#FFFFFF" : theme.glyph);
    ctx.setStrokeColor(new Color(strokeColor, theme.frost ? 0.5 : 1));
    ctx.setLineWidth(Math.max(2, Math.round(S * 0.03)));
    ctx.strokePath();
  }
  if (theme.dots) {
    const spots = [[0.2, 0.2], [0.82, 0.24], [0.16, 0.7], [0.8, 0.78], [0.3, 0.86]];
    for (let d = 0; d < spots.length; d++) {
      ctx.setFillColor(new Color((d + index) % 2 ? "#27C4F5" : "#FF2E92"));
      const dr = Math.max(1.5, S * 0.02);
      ctx.fillEllipse(new Rect(spots[d][0] * S - dr, spots[d][1] * S - dr, dr * 2, dr * 2));
    }
  }
  if (theme.wordTile) {
    const word = String(app.label || "App").trim() || "App";
    const fs = Math.min(S * 0.3, (S * 0.8) / (word.length * 0.48));
    const wc = theme.wordColors ? theme.wordColors[index % theme.wordColors.length] : theme.glyph;
    ctx.setTextColor(new Color(wc));
    ctx.setFont(fontFor(theme.wordStyle || "serif", Math.round(fs), false));
    ctx.setTextAlignedCenter();
    ctx.drawTextInRect(word, new Rect(0, S * 0.5 - fs * 0.72, S, fs * 1.5));
    return ctx.getImage();
  }
  if (theme.glyphStyle === "line") {
    let strokes = vglyphFor(app.label);
    if (strokes && (theme.thick || theme.glow)) {
      strokes = strokes.filter(function (st) {
        return !(Array.isArray(st[0]) && st[0][0] === "c" && st[0][3] < 0.035);
      });
    }
    const gA = theme.gradStroke ? theme.gradStroke[0] : glyphColor;
    const gB = theme.gradStroke ? theme.gradStroke[1] : null;
    const lineW = Math.max(2, S * (theme.thick ? 0.085 : 0.045));
    const gScale = theme.ring ? S * 0.5 : S * 0.92;
    if (theme.ring) {
      ctx.setStrokeColor(new Color(gA));
      ctx.setLineWidth(Math.max(2, S * 0.035));
      ctx.strokeEllipse(new Rect(S * 0.14, S * 0.14, S * 0.72, S * 0.72));
    }
    if (strokes) {
      if (theme.glow) {
        // No blur in DrawContext — layered wide strokes fake the neon halo.
        strokeVGlyph(ctx, strokes, S / 2, S / 2, gScale, lineW * 3.2, gA, gB, 0.16);
        strokeVGlyph(ctx, strokes, S / 2, S / 2, gScale, lineW * 1.9, gA, gB, 0.35);
      }
      strokeVGlyph(ctx, strokes, S / 2, S / 2, gScale, lineW, gA, gB, 1);
    } else {
      ctx.setTextColor(new Color(gA));
      ctx.setFont(fontFor("serif", Math.round(S * (theme.ring ? 0.32 : 0.46)), theme.thick === true));
      ctx.setTextAlignedCenter();
      ctx.drawTextInRect((app.label || "A").trim().charAt(0).toLowerCase(), new Rect(0, S * (theme.ring ? 0.32 : 0.2), S, S * 0.64));
    }
    return ctx.getImage();
  }
  // Letters are the fallback, not the aesthetic — recognized apps get their
  // vector glyph (retro monograms and emoji tiles opt out via flags).
  const symStrokes = (theme.emojiTile || theme.lettersOnly) ? null : vglyphFor(app.label);
  if (symStrokes) {
    strokeVGlyph(ctx, symStrokes, S / 2, S / 2, S * 0.6, Math.max(2, S * 0.055), glyphColor, null, 1);
    return ctx.getImage();
  }
  const glyph = iconGlyph(app, themeName);
  ctx.setTextColor(new Color(glyphColor));
  ctx.setFont(theme.emojiTile ? Font.systemFont(Math.round(S * 0.5)) : Font.boldSystemFont(Math.round(S * 0.42)));
  ctx.setTextAlignedCenter();
  ctx.drawTextInRect(glyph, new Rect(0, S * (theme.emojiTile ? 0.18 : 0.22), S, S * 0.62));
  return ctx.getImage();
}
async function loadIcon(url) {
  try {
    // Widgets have a hard memory cap — ten 512px icons plus a full-res
    // wallpaper crop can kill the run (iOS then shows a stale snapshot
    // forever). Ask iTunes for small artwork and cache a 216px version.
    url = url.replace(/\/[0-9]{3,4}x[0-9]{3,4}(bb)?\./, "/216x216bb.");
    const fm = FileManager.local();
    const dir = fm.cacheDirectory();
    // Hash the FULL url — icon URLs share identical endings across apps, so
    // suffix-based names collide and serve the wrong app's icon.
    const name = "wk3_" + hashString(url) + "_" + url.length + ".png";
    const path = fm.joinPath(dir, name);
    if (fm.fileExists(path)) return fm.readImage(path);
    let img = await new Request(url).loadImage();
    if (img && img.size && img.size.width > 240) {
      const dc = new DrawContext();
      dc.size = new Size(216, 216);
      dc.opaque = false;
      dc.respectScreenScale = false;
      dc.drawImageInRect(img, new Rect(0, 0, 216, 216));
      img = dc.getImage();
    }
    fm.writeImage(path, img);
    return img;
  } catch (e) { return null; }
}
async function buildLauncher(w, design, family, tc, style) {
  const apps = (design.apps || []).slice(0, 12);
  if (apps.length === 0) { centeredText(w, "Add apps in the designer", fontFor(style, 13, true), tc); return; }
  const ls = design.launcherStyle || {};
  const iconPt = Math.min(Math.max(Number(ls.iconSize) || 30, 16), 120);
  const showLabels = ls.labels !== false;
  const radius = ls.shape === "circle" ? iconPt / 2 : Math.round(iconPt * 0.24);
  const columns = Math.min(Math.max(Math.round(Number(ls.columns) || 0), 0), 6);
  const perRow = columns > 0 ? columns : (family === "small" ? 2 : 4);
  const labelPt = Math.min(13, Math.max(9, Math.round(iconPt * 0.22)));
  // Whole-widget fallback URL: a tap on empty space (or anywhere on a Small
  // widget) opens the first app instead of bouncing into Scriptable.
  if (apps[0].url && !w.url) w.url = apps[0].url;
  // Deterministic layout: every margin and gap is a computed fixed number of
  // points — the same math the designer preview uses — because flexible
  // spacers distribute differently across iOS versions (preview mismatch).
  const dims = widgetPointSizes(family);
  const W = dims[0], H = dims[1];
  const pad = 12;
  const rowGap = 10;
  w.setPadding(0, 0, 0, 0);
  const root = w.addStack();
  root.layoutVertically();
  root.size = new Size(W, H);
  const cellH = iconPt + (showLabels ? labelPt + 3 : 0);
  const rowCount = Math.ceil(apps.length / perRow);
  const contentH = rowCount * cellH + (rowCount - 1) * rowGap;
  root.addSpacer(Math.max(0, (H - contentH) / 2));
  for (let i = 0; i < apps.length; i += perRow) {
    if (i > 0) root.addSpacer(rowGap);
    const rowApps = apps.slice(i, i + perRow);
    const n = rowApps.length;
    const gap = Math.max(0, (W - 2 * pad - n * iconPt) / (n + 1));
    const rowStack = root.addStack();
    rowStack.layoutHorizontally();
    rowStack.topAlignContent();
    rowStack.size = new Size(W, cellH);
    rowStack.addSpacer(pad + gap);
    for (let j = 0; j < n; j++) {
      const app = rowApps[j];
      if (j > 0) rowStack.addSpacer(gap);
      const cell = rowStack.addStack();
      cell.layoutVertically();
      cell.centerAlignContent();
      cell.size = new Size(iconPt, cellH);
      if (app.url) cell.url = app.url;
      const iconTheme = ls.iconTheme && ICON_THEMES[ls.iconTheme] ? ls.iconTheme : "real";
      let realIcon = null;
      if (iconTheme !== "real") {
        const tile = cell.addImage(themedIconTile(app, iconTheme, i + j, iconPt));
        tile.imageSize = new Size(iconPt, iconPt);
      } else {
        if (app.iconB64) { try { realIcon = Image.fromData(Data.fromBase64String(app.iconB64)); } catch (e) {} }
        if (!realIcon && app.iconUrl) realIcon = await loadIcon(app.iconUrl);
        if (realIcon) {
          const img = cell.addImage(realIcon);
          img.imageSize = new Size(iconPt, iconPt);
          img.cornerRadius = radius;
        } else {
          const icon = cell.addText(app.emoji || "🌐");
          icon.font = Font.systemFont(Math.round(iconPt * 0.9));
          icon.centerAlignText();
        }
      }
      if (showLabels) {
        cell.addSpacer(3);
        const label = cell.addText(app.label || "App");
        label.font = fontFor(style, labelPt, false);
        label.textColor = tc;
        label.textOpacity = 0.85;
        label.lineLimit = 1;
        label.minimumScaleFactor = 0.6;
        label.centerAlignText();
      }
    }
    rowStack.addSpacer(pad + gap);
  }
  root.addSpacer(Math.max(0, (H - contentH) / 2));
}
// Lock Screen (accessory) widgets: iOS renders them in vibrant monochrome and
// supplies the background, so rows of NATIVE text keep them crisp — no baked
// images. Time and countdown rows use system date text, so they stay live.
async function buildLockWidget(design, family) {
  const w = new ListWidget();
  w.setPadding(2, 2, 2, 2);
  if (design.tapUrl) w.url = design.tapUrl;
  const style = design.fontStyle || "rounded";
  const circle = family === "accessoryCircular";
  let rows = Array.isArray(design.lockRows) ? design.lockRows.slice(0, circle ? 2 : 3) : [];
  if (!rows.length) {
    // Any regular design still works on the Lock Screen — map it to rows.
    if (design.kind === "clock") rows = [{ kind: "time" }, { kind: "date" }];
    else if (design.kind === "countdown") rows = [
      { kind: "text", text: design.primaryText || design.name || "Countdown" },
      { kind: "countdown", dateISO: design.targetDate }];
    else if (design.kind === "battery") rows = [{ kind: "battery" }];
    else if (design.kind === "date") rows = [{ kind: "date" }];
    else rows = [{ kind: "text", text: design.primaryText || design.name || "WidgetKing" }];
  }
  const live = {};
  if (rows.some(function (r) { return r.kind === "weather"; })) live.weather = await fetchWeather();
  if (rows.some(function (r) { return r.kind === "reminder"; })) live.reminders = await fetchReminders(1);
  w.addSpacer();
  for (const row of rows) {
    const big = rows.length === 1 || (rows.length > 1 && row === rows[0] && circle);
    const size = big ? (circle ? 20 : 18) : (rows.length >= 3 ? 10 : 12);
    const fnt = fontFor(style, size, row === rows[0]);
    if (row.kind === "time") {
      const t = w.addDate(new Date());
      t.applyTimeStyle(); t.font = fnt; t.textColor = new Color("#FFFFFF");
      t.centerAlignText(); t.minimumScaleFactor = 0.5; t.lineLimit = 1;
    } else if (row.kind === "date") {
      const t = w.addDate(new Date());
      t.applyDateStyle(); t.font = fnt; t.textColor = new Color("#FFFFFF");
      t.centerAlignText(); t.minimumScaleFactor = 0.5; t.lineLimit = 1;
    } else if (row.kind === "countdown") {
      const iso = row.dateISO || design.targetDate;
      if (iso) {
        const t = w.addDate(new Date(iso + "T00:00:00"));
        t.applyRelativeStyle(); t.font = fnt; t.textColor = new Color("#FFFFFF");
        t.centerAlignText(); t.minimumScaleFactor = 0.5; t.lineLimit = 1;
      } else {
        const t = w.addText("Set a date");
        t.font = fnt; t.textColor = new Color("#FFFFFF"); t.centerAlignText();
      }
    } else {
      let str = "";
      if (row.kind === "battery") {
        let lvl = 80;
        try { lvl = Math.round(Device.batteryLevel() * 100); } catch (e) {}
        str = "🔋 " + lvl + "%";
      } else if (row.kind === "weather") { str = weatherText({ unit: row.unit || "f" }, live.weather); }
      else if (row.kind === "reminder") {
        str = live.reminders && live.reminders.length ? "○ " + live.reminders[0].title
          : (live.reminders ? "All done ✓" : "Reminders off");
      } else { str = String(row.text || ""); }
      const t = w.addText(str);
      t.font = fnt; t.textColor = new Color("#FFFFFF");
      t.centerAlignText(); t.minimumScaleFactor = 0.5; t.lineLimit = 1;
    }
  }
  w.addSpacer();
  w.refreshAfterDate = new Date(Date.now() + 15 * 60 * 1000);
  return w;
}
async function buildWidget(design, position) {
  const family = config.widgetFamily || "small";
  if (String(family).indexOf("accessory") === 0) {
    return buildLockWidget(design, family);
  }
  const w = new ListWidget();
  w.setPadding(12, 12, 12, 12);
  const bgImg = backgroundImageFor(design, family, position);
  if (bgImg && design.kind !== "freestyle") {
    w.backgroundImage = bgImg;
  } else if (!bgImg && design.kind !== "freestyle") {
    // Freestyle paints its own background INTO its image — setting a widget
    // gradient too would layer ON TOP of that image (Scriptable draws
    // backgroundGradient above backgroundImage), hiding every element.
    const colors = themeColors(design);
    const g = new LinearGradient();
    g.colors = [new Color(colors[0]), new Color(colors[1])];
    g.locations = [0, 1];
    g.startPoint = new Point(0, 0);
    g.endPoint = design.gradientDir === "vertical" ? new Point(0, 1)
      : design.gradientDir === "horizontal" ? new Point(1, 0) : new Point(1, 1);
    w.backgroundGradient = g;
  }
  const tc = new Color(design.textColorHex || "#FFFFFF");
  const style = design.fontStyle || "rounded";
  if (design.tapUrl) w.url = design.tapUrl;
  if (design.kind === "freestyle") {
    w.setPadding(0, 0, 0, 0);
    const live = await liveDataFor(design);
    w.backgroundImage = drawFreestyle(design, family, bgImg, live);
    await addFreestyleApps(w, design, family, live);
    w.refreshAfterDate = new Date(Date.now() + 5 * 60 * 1000);
    return w;
  }
  if (design.kind === "launcher") {
    await buildLauncher(w, design, family, tc, style);
    return w;
  }
  w.addSpacer();
  switch (design.kind) {
    case "clock": {
      const t = w.addDate(new Date());
      t.applyTimeStyle(); t.font = fontFor(style, 40, true); t.textColor = tc;
      t.centerAlignText(); t.minimumScaleFactor = 0.4;
      const d = w.addDate(new Date());
      d.applyDateStyle(); d.font = fontFor(style, 12, false); d.textColor = tc;
      d.textOpacity = 0.85; d.centerAlignText();
      break;
    }
    case "date": {
      const now = new Date();
      const wd = new DateFormatter(); wd.dateFormat = "EEEE";
      const mo = new DateFormatter(); mo.dateFormat = "MMMM";
      centeredText(w, wd.string(now).toUpperCase(), fontFor(style, 13, true), tc).textOpacity = 0.85;
      centeredText(w, String(now.getDate()), fontFor(style, 50, true), tc);
      centeredText(w, mo.string(now), fontFor(style, 13, false), tc).textOpacity = 0.85;
      break;
    }
    case "countdown": {
      const days = daysUntil(design.targetDate);
      centeredText(w, design.primaryText || design.name || "Countdown", fontFor(style, 13, true), tc).textOpacity = 0.85;
      centeredText(w, String(Math.abs(days)), fontFor(style, 44, true), tc);
      centeredText(w, days >= 0 ? "days to go" : "days ago", fontFor(style, 11, false), tc).textOpacity = 0.75;
      break;
    }
    case "quote": {
      centeredText(w, "“", fontFor(style, 18, true), tc).textOpacity = 0.6;
      centeredText(w, activeQuote(design) || "Add a quote", fontFor(style, 15, true), tc);
      if (design.secondaryText) {
        centeredText(w, "— " + design.secondaryText, fontFor(style, 11, false), tc).textOpacity = 0.75;
      }
      break;
    }
    case "battery": {
      const level = Math.round(Device.batteryLevel() * 100);
      centeredText(w, "🔋", Font.systemFont(22), tc);
      centeredText(w, level + "%", fontFor(style, 40, true), tc);
      centeredText(w, Device.isCharging() ? "charging" : "battery", fontFor(style, 11, false), tc).textOpacity = 0.75;
      break;
    }
    default: {
      centeredText(w, design.primaryText || design.name || "WidgetKing", fontFor(style, 18, true), tc);
    }
  }
  w.addSpacer();
  w.refreshAfterDate = new Date(Date.now() + 5 * 60 * 1000);
  return w;
}
