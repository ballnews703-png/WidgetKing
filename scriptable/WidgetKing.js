// True widget dimensions in points for THIS device, derived from the
// measured pixel frames (frame px / screen scale). Assuming a generic size
// makes iOS stretch the layout — the spacing then looks nothing like the
// designer preview.
// Which frame table applies to THIS iPhone: the user's explicit model pick
// beats auto-detection from the hardware.
function frameEntryKey() {
  const prefs = loadPrefs();
  if (prefs.screenKey && SCREEN_FRAMES[String(prefs.screenKey)]) return String(prefs.screenKey);
  try {
    const hPx = Math.round(Math.max(Device.screenSize().width, Device.screenSize().height) * Device.screenScale());
    if (SCREEN_FRAMES[String(hPx)]) return String(hPx);
  } catch (e) {}
  return "";
}
function widgetPointSizes(family) {
  try {
    const scale = Device.screenScale();
    const entry = SCREEN_FRAMES[frameEntryKey()];
    if (entry) {
      const f = (loadPrefs().iconLabels === false && entry.nolabels) ? entry.nolabels : entry.labels;
      const small = f[0] / scale, med = f[1] / scale, large = f[2] / scale;
      if (family === "medium") return [med, small];
      if (family === "large") return [med, large];
      return [small, small];
    }
  } catch (e) {}
  const PT = { small: [155, 155], medium: [329, 155], large: [329, 345] };
  return PT[family] || PT.small;
}
function widgetRect(imgW, imgH, family, position) {
  const pos = position || (family === "small" ? "top-left" : "top");
  const posParts = pos.split("-");
  const row = posParts[0] || "top";
  const side = posParts[1] || "left";
  // Identify the device first (model pick / hardware), not the screenshot:
  // resized or iCloud-optimized screenshots must not land in the wrong row.
  let key = frameEntryKey();
  if (!key && SCREEN_FRAMES[String(Math.round(imgH))]) key = String(Math.round(imgH));
  const entry = SCREEN_FRAMES[key];
  let x, y, w, h, rows;
  if (entry) {
    const raw = (loadPrefs().iconLabels === false && entry.nolabels) ? entry.nolabels : entry.labels;
    // If the saved image was scaled down, scale the frame with it.
    const sc = imgH / Number(key);
    const f = raw.map(function (v) { return v * sc; });
    rows = { top: f[5], middle: f[6], bottom: f[7] };
    x = f[3];
    w = h = f[0];
    if (family === "small") {
      x = side === "right" ? f[4] : f[3];
    } else if (family === "medium") {
      w = f[1];
    } else if (family === "large") {
      w = f[1]; h = f[2];
    }
  } else {
    // Unknown screenshot size (e.g. a scaled photo) — proportional fallback.
    const sw = Math.round(imgW * 0.402);
    const gap = Math.round((imgW - 2 * sw) / 3);
    const rowStep = sw + gap;
    const top = Math.round(imgH * 0.0965);
    rows = { top: top, middle: top + rowStep, bottom: top + 2 * rowStep };
    x = gap;
    w = h = sw;
    if (family === "small") {
      x = side === "right" ? gap * 2 + sw : gap;
    } else if (family === "medium") {
      w = imgW - 2 * gap;
    } else if (family === "large") {
      w = imgW - 2 * gap; h = sw * 2 + gap;
    }
  }
  y = rows[row] != null ? rows[row] : rows.top;
  if (family === "large" && row === "bottom") y = rows.middle;
  // User-tuned fine alignment from the in-app "Nudge" menu.
  const prefs = loadPrefs();
  y += Number(prefs.offsetY) || 0;
  x += Number(prefs.offsetX) || 0;
  x = Math.min(Math.max(0, x), Math.max(0, imgW - w));
  if (y + h > imgH) y = Math.max(0, imgH - h);
  if (y < 0) y = 0;
  return new Rect(x, y, w, h);
}
function cropImage(img, rect) {
  const ctx = new DrawContext();
  ctx.size = new Size(rect.width, rect.height);
  ctx.opaque = true;
  ctx.respectScreenScale = false;
  ctx.drawImageAtPoint(img, new Point(-rect.x, -rect.y));
  return ctx.getImage();
}
// Poor-man's gaussian: downscale then upscale.
function blurImage(img) {
  const w = img.size.width, h = img.size.height;
  const smallCtx = new DrawContext();
  const dw = Math.max(2, Math.round(w / 16));
  const dh = Math.max(2, Math.round(h / 16));
  smallCtx.size = new Size(dw, dh);
  smallCtx.opaque = true;
  smallCtx.respectScreenScale = false;
  smallCtx.drawImageInRect(img, new Rect(0, 0, dw, dh));
  const soft = smallCtx.getImage();
  const bigCtx = new DrawContext();
  bigCtx.size = new Size(w, h);
  bigCtx.opaque = true;
  bigCtx.respectScreenScale = false;
  bigCtx.drawImageInRect(soft, new Rect(0, 0, w, h));
  return bigCtx.getImage();
}
function tintImage(img, dark, strength) {
  const s = (typeof strength === "number" && strength >= 0.1 && strength <= 1) ? strength : 1;
  const ctx = new DrawContext();
  ctx.size = img.size;
  ctx.opaque = true;
  ctx.respectScreenScale = false;
  ctx.drawImageInRect(img, new Rect(0, 0, img.size.width, img.size.height));
  ctx.setFillColor(dark ? new Color("#101018", 0.32 * s) : new Color("#FFFFFF", 0.25 * s));
  ctx.fillRect(new Rect(0, 0, img.size.width, img.size.height));
  return ctx.getImage();
}
// Paints the design's gradient at partial opacity over a wallpaper slice —
// the "see-through gradient" background. Strips must not overlap or the
// seams double-blend into visible lines.
function gradientOver(img, design, alpha) {
  const w = img.size.width, h = img.size.height;
  const ctx = new DrawContext();
  ctx.size = img.size;
  ctx.opaque = true;
  ctx.respectScreenScale = false;
  ctx.drawImageInRect(img, new Rect(0, 0, w, h));
  const colors = themeColors(design);
  const c1 = hexToRgb(colors[0]); const c2 = hexToRgb(colors[1]);
  const steps = 60;
  const horizontal = design.gradientDir === "horizontal";
  const span = horizontal ? w : h;
  for (let i = 0; i < steps; i++) {
    const t = i / (steps - 1);
    const mix = [0, 1, 2].map(function (j) { return c1[j] + (c2[j] - c1[j]) * t; });
    ctx.setFillColor(new Color(rgbToHex(mix), alpha));
    const a = Math.floor((span * i) / steps);
    const b = Math.floor((span * (i + 1)) / steps);
    if (horizontal) { ctx.fillRect(new Rect(a, 0, b - a, h)); }
    else { ctx.fillRect(new Rect(0, a, w, b - a)); }
  }
  return ctx.getImage();
}
function bgOpacityOf(design) {
  const op = Number(design.bgOpacity);
  return (isFinite(op) && op >= 0.1 && op < 1) ? op : 1;
}
function backgroundImageFor(design, family, position) {
  const op = bgOpacityOf(design);
  const glassy = design.background === "glass" || design.background === "clear";
  const blend = design.background === "gradient" && op < 1;
  if (!glassy && !blend) return null;
  const wall = loadWallpaper();
  if (!wall) return null;
  let rect;
  if (position || design.background === "clear") {
    // Clear must always slice a real widget frame — without a position it
    // assumes the top spot (set "Name | position" in the Parameter to fix).
    rect = widgetRect(wall.size.width, wall.size.height, family, position);
  } else {
    const aspect = family === "medium" ? 2.14 : family === "large" ? 0.955 : 1;
    let w = wall.size.width * 0.86;
    let h = w / aspect;
    if (h > wall.size.height * 0.8) { h = wall.size.height * 0.8; w = h * aspect; }
    rect = new Rect((wall.size.width - w) / 2, (wall.size.height - h) / 2, w, h);
  }
  let img = cropImage(wall, rect);
  if (design.background === "glass") {
    img = blurImage(img);
    img = tintImage(img, (design.glassTint || "dark") !== "light", op);
  } else if (blend) {
    img = gradientOver(img, design, op);
  }
  return img;
}

function drawFreestyle(design, family, bgImg, live) {
  // Draw at the device's true widget size (in pixels) so nothing stretches.
  const pts = widgetPointSizes(family);
  let s = 3;
  try { s = Device.screenScale() || 3; } catch (e) {}
  const W = Math.round(pts[0] * s), H = Math.round(pts[1] * s);
  const ctx = new DrawContext();
  ctx.size = new Size(W, H); ctx.opaque = false; ctx.respectScreenScale = false;
  if (bgImg) {
    ctx.drawImageInRect(bgImg, new Rect(0, 0, W, H));
  } else {
    const colors = themeColors(design);
    const c1 = hexToRgb(colors[0]); const c2 = hexToRgb(colors[1]);
    const steps = 60;
    const horizontal = design.gradientDir === "horizontal";
    for (let i = 0; i < steps; i++) {
      const t = i / (steps - 1);
      const mix = [0, 1, 2].map(function (j) { return c1[j] + (c2[j] - c1[j]) * t; });
      ctx.setFillColor(new Color(rgbToHex(mix)));
      if (horizontal) {
        ctx.fillRect(new Rect(Math.floor((W * i) / steps), 0, Math.ceil(W / steps) + 1, H));
      } else {
        ctx.fillRect(new Rect(0, Math.floor((H * i) / steps), W, Math.ceil(H / steps) + 1));
      }
    }
  }
  const scale = Math.min(W, H) / 158;
  const els = design.canvasElements || [];
  for (const el of els) {
    // Clocks and countdowns render as live native overlays, never baked.
    if (el.kind === "clock" || el.kind === "countdown") continue;
    const px = el.x * W; const py = el.y * H; const fs = (el.size || 20) * scale;
    const op = (typeof el.opacity === "number" && el.opacity >= 0 && el.opacity <= 1) ? el.opacity : 1;
    if (el.kind === "shape") {
      const shapeType = el.shape || "rect";
      let wPx, hPx;
      if (shapeType === "circle") { wPx = hPx = (el.w || 0.5) * Math.min(W, H); }
      else { wPx = (el.w || 0.5) * W; hPx = (el.h || 0.25) * H; }
      const rect = new Rect(px - wPx / 2, py - hPx / 2, wPx, hPx);
      const rr2 = shapeType === "pill" ? Math.min(wPx, hPx) / 2
        : (typeof el.radius === "number" ? el.radius * scale : 6 * scale);
      if (op > 0.02) {
        ctx.setFillColor(new Color(el.colorHex || "#FFFFFF", op));
        const path = new Path();
        if (shapeType === "circle") { path.addEllipse(rect); }
        else { path.addRoundedRect(rect, rr2, rr2); }
        ctx.addPath(path);
        ctx.fillPath();
      }
      const bw = (Number(el.border) || 0) * scale;
      if (bw > 0) {
        ctx.setStrokeColor(new Color(el.borderHex || el.colorHex || "#FFFFFF", 1));
        ctx.setLineWidth(bw);
        const inset = bw / 2;
        const srect = new Rect(rect.x + inset, rect.y + inset, rect.width - bw, rect.height - bw);
        const spath = new Path();
        if (shapeType === "circle") { spath.addEllipse(srect); }
        else { spath.addRoundedRect(srect, Math.max(0, rr2 - inset), Math.max(0, rr2 - inset)); }
        ctx.addPath(spath);
        ctx.strokePath();
      }
      continue;
    }
    if (el.kind === "photo") {
      // Photos arrive pre-baked from the designer: crop shape and opacity are
      // already burned into the PNG's pixels/alpha, so we just draw it.
      // Multiple photos rotate daily or on every widget refresh.
      const list = (Array.isArray(el.b64s) && el.b64s.length) ? el.b64s : (el.b64 ? [el.b64] : []);
      if (list.length) {
        let idx = 0;
        if (list.length > 1) {
          idx = el.rotate === "refresh"
            ? Math.floor(Math.random() * list.length)
            : dayOfYear(new Date()) % list.length;
        }
        try {
          const img = Image.fromData(Data.fromBase64String(list[idx]));
          let wPx, hPx;
          if (el.shape === "circle") { wPx = hPx = (el.w || 0.55) * Math.min(W, H); }
          else { wPx = (el.w || 0.55) * W; hPx = wPx * (el.aspect || 1); }
          ctx.drawImageInRect(img, new Rect(px - wPx / 2, py - hPx / 2, wPx, hPx));
        } catch (e) {}
      } else {
        // No image data made it into the script (photos don't travel in sync
        // links) — say so on the widget instead of leaving a silent hole.
        // Mid-gray on a translucent chip stays readable on ANY background
        // (white-on-cream was invisible).
        ctx.setFillColor(new Color("#808080", 0.25));
        const chipPath = new Path();
        chipPath.addRoundedRect(new Rect(px - 74, py - 10, 148, 20), 10, 10);
        ctx.addPath(chipPath);
        ctx.fillPath();
        ctx.setFont(Font.mediumSystemFont(9));
        ctx.setTextColor(new Color("#606060", 0.95));
        ctx.setTextAlignedCenter();
        ctx.drawTextInRect("photo missing - re-add in designer", new Rect(px - 70, py - 6, 140, 14));
      }
      continue;
    }
    if (el.kind === "art") {
      // Pre-baked in the designer (curved/rotated text, gradients) — just draw.
      if (el.b64 && el.artW) {
        try {
          const img = Image.fromData(Data.fromBase64String(el.b64));
          const wPx = el.artW * scale, hPx = (el.artH || el.artW) * scale;
          ctx.drawImageInRect(img, new Rect(px - wPx / 2, py - hPx / 2, wPx, hPx));
        } catch (e) {}
      } else {
        ctx.setFont(Font.mediumSystemFont(9));
        ctx.setTextColor(new Color("#606060", 0.95));
        ctx.drawTextInRect("art missing - re-copy the script", new Rect(px - 70, py - 6, 140, 14));
      }
      continue;
    }
    if (el.kind === "progress") {
      const pct = Math.min(Math.max(progressPct(el), 0), 1);
      const wPx = (el.w || 0.7) * W;
      const hPx = Math.max(3 * scale, (el.size || 8) * scale);
      const x0 = px - wPx / 2, y0 = py - hPx / 2;
      const r = hPx / 2;
      ctx.setFillColor(new Color(el.colorHex || "#FFFFFF", op * 0.25));
      const track = new Path();
      track.addRoundedRect(new Rect(x0, y0, wPx, hPx), r, r);
      ctx.addPath(track);
      ctx.fillPath();
      if (pct > 0.02) {
        ctx.setFillColor(new Color(el.colorHex || "#FFFFFF", op));
        const fill = new Path();
        fill.addRoundedRect(new Rect(x0, y0, Math.max(hPx, wPx * pct), hPx), r, r);
        ctx.addPath(fill);
        ctx.fillPath();
      }
      continue;
    }
    if (el.kind === "ring") {
      // Progress ring: polyline arc (DrawContext has no arc API). Track
      // circle at low alpha, then the progress sweep from 12 o'clock.
      const pct = Math.min(Math.max(progressPct(el), 0), 1);
      const dia = (el.w || 0.55) * Math.min(W, H);
      const radius2 = dia / 2;
      const stroke = Math.max(2 * scale, (el.size || 7) * scale);
      const rr = radius2 - stroke / 2;
      ctx.setLineWidth(stroke);
      function ringPath(fromT, toT) {
        const path = new Path();
        const steps = Math.max(8, Math.round(72 * (toT - fromT)));
        for (let s2 = 0; s2 <= steps; s2++) {
          const a = -Math.PI / 2 + 2 * Math.PI * (fromT + (toT - fromT) * (s2 / steps));
          const ptx = px + rr * Math.cos(a);
          const pty = py + rr * Math.sin(a);
          if (s2 === 0) path.move(new Point(ptx, pty)); else path.addLine(new Point(ptx, pty));
        }
        return path;
      }
      ctx.setStrokeColor(new Color(el.colorHex || "#FFFFFF", op * 0.25));
      ctx.addPath(ringPath(0, 1));
      ctx.strokePath();
      if (pct > 0.01) {
        ctx.setStrokeColor(new Color(el.colorHex || "#FFFFFF", op));
        ctx.addPath(ringPath(0, pct));
        ctx.strokePath();
      }
      continue;
    }
    if (el.kind === "month") {
      // Mini month calendar: weekday header + date grid, today circled.
      const fsM = (el.size || 9) * scale;
      const gw = (el.w || 0.6) * W;
      const cell = gw / 7;
      const now2 = new Date();
      const first = new Date(now2.getFullYear(), now2.getMonth(), 1);
      const startDow = first.getDay();
      const daysIn = new Date(now2.getFullYear(), now2.getMonth() + 1, 0).getDate();
      const rows = Math.ceil((startDow + daysIn) / 7);
      const rowH = fsM * 1.7;
      const gh = rowH * (rows + 1);
      const x0 = px - gw / 2, y0 = py - gh / 2;
      const headers = ["S", "M", "T", "W", "T", "F", "S"];
      ctx.setTextAlignedCenter();
      ctx.setFont(fontFor(el.font || design.fontStyle, fsM * 0.9, true));
      ctx.setTextColor(new Color(el.colorHex || "#FFFFFF", op * 0.6));
      for (let c = 0; c < 7; c++) {
        ctx.drawTextInRect(headers[c], new Rect(x0 + c * cell, y0, cell, rowH));
      }
      const prevDays = new Date(now2.getFullYear(), now2.getMonth(), 0).getDate();
      ctx.setFont(fontFor(el.font || design.fontStyle, fsM, false));
      ctx.setTextColor(new Color(el.colorHex || "#FFFFFF", op * 0.3));
      for (let b = 0; b < startDow; b++) {
        ctx.drawTextInRect(String(prevDays - startDow + 1 + b),
          new Rect(x0 + b * cell, y0 + rowH + (rowH - fsM * 1.4) / 2, cell, fsM * 1.4));
      }
      const tail = rows * 7 - (startDow + daysIn);
      for (let a = 0; a < tail; a++) {
        const idx2 = startDow + daysIn + a;
        ctx.drawTextInRect(String(a + 1),
          new Rect(x0 + (idx2 % 7) * cell, y0 + (Math.floor(idx2 / 7) + 1) * rowH + (rowH - fsM * 1.4) / 2, cell, fsM * 1.4));
      }
      for (let d = 1; d <= daysIn; d++) {
        const idx = startDow + d - 1;
        const r = Math.floor(idx / 7), c = idx % 7;
        const cx2 = x0 + c * cell, cy2 = y0 + (r + 1) * rowH;
        if (d === now2.getDate()) {
          ctx.setFillColor(new Color(el.accentHex || "#4A90F6", op));
          const dia = Math.min(cell, rowH) * 0.95;
          ctx.fillEllipse(new Rect(cx2 + (cell - dia) / 2, cy2 + (rowH - dia) / 2, dia, dia));
          ctx.setFont(fontFor(el.font || design.fontStyle, fsM, true));
          ctx.setTextColor(new Color("#FFFFFF", 1));
        } else {
          ctx.setFont(fontFor(el.font || design.fontStyle, fsM, false));
          ctx.setTextColor(new Color(el.colorHex || "#FFFFFF", op * 0.9));
        }
        ctx.drawTextInRect(String(d), new Rect(cx2, cy2 + (rowH - fsM * 1.4) / 2, cell, fsM * 1.4));
      }
      continue;
    }
    if (el.kind === "app" || el.kind === "sleeperlogo") continue; // rendered as overlay stacks
    let text;
    let liveColor = null; // e.g. stock green/red decided by live data
    if (el.kind === "clock") { const df = new DateFormatter(); df.useShortTimeStyle(); text = df.string(new Date()); }
    else if (el.kind === "date") { const df = new DateFormatter(); df.dateFormat = "EEE MMM d"; text = df.string(new Date()); }
    else if (el.kind === "battery") { text = Math.round(Device.batteryLevel() * 100) + "%"; }
    else if (el.kind === "countdown") { text = String(Math.abs(daysUntil(el.dateISO))); }
    else if (el.kind === "symbol") { text = SYMBOL_EMOJI[el.symbolName] || "⭐"; }
    else if (el.kind === "icon") { text = el.text || "★"; }
    else if (el.kind === "weather") { text = weatherText(el, live ? live.weather : null); }
    else if (el.kind === "calendar") { text = calendarText(el, live ? live.events : null); }
    else if (el.kind === "sleeper") { text = sleeperText(el, live && live.sleeper ? live.sleeper[el.leagueID] : null); }
    else if (el.kind === "astro") { text = astroText(el, live ? live.astro : null); }
    else if (el.kind === "stock") {
      const q = live && live.stocks ? live.stocks[String(el.symbol || "").trim().toUpperCase()] : null;
      text = stockText(el, q);
      if (el.autoColor !== false && q && isFinite(q.pct)) {
        liveColor = q.pct >= 0 ? "#30D158" : "#FF6961";
      }
    }
    else if (el.kind === "worldclock") { text = worldClockText(el, new Date()); }
    else if (el.kind === "reminders") { text = remindersText(el, live ? live.reminders : null); }
    else if (el.kind === "news") { text = newsText(el, live ? live.news : null); }
    else if (el.kind === "greeting") { text = greetingText(el); }
    else if (el.kind === "week") { text = "Week " + weekNumber(new Date()); }
    else { text = el.text || "Text"; }
    // multi:"day" — a text element holding several lines shows one per day.
    if (el.kind === "text" && el.multi === "day" && text.indexOf("\n") >= 0) {
      const qlines = text.split("\n").map(function (s) { return s.trim(); }).filter(Boolean);
      if (qlines.length) text = qlines[dayOfYear(new Date()) % qlines.length];
    }
    const isBold = el.kind !== "text" || el.bold !== false;
    ctx.setFont(fontFor(el.font || design.fontStyle, fs, isBold));
    ctx.setTextColor(new Color(liveColor || el.colorHex || "#FFFFFF", el.kind === "emoji" ? 1 : op));
    if (el.kind === "text" && el.w > 0) {
      // Text box: fixed width, wraps, top-anchored — mirrors the designer.
      if (el.align === "left") { ctx.setTextAlignedLeft(); }
      else if (el.align === "right") { ctx.setTextAlignedRight(); }
      else { ctx.setTextAlignedCenter(); }
      const boxW = el.w * W;
      ctx.drawTextInRect(text, new Rect(px - boxW / 2, py - fs * 0.72, boxW, H));
    } else {
      ctx.setTextAlignedCenter();
      const lines = (el.kind === "calendar" || el.kind === "reminders" || el.kind === "news")
        ? Math.min(Math.max(Number(el.count) || 1, 1), 4) : 1;
      ctx.drawTextInRect(text, new Rect(px - W / 2, py - fs * 0.72, W, fs * 1.7 * lines));
    }
  }
  return ctx.getImage();
}
// App elements in freestyle designs are laid over the drawn background as
// real stacks, so they get crisp rounded icons AND per-icon tap targets
// (iOS allows multiple tap targets on medium/large widgets only).
// Native overlay cell footprint [w, h] in points. Clocks and countdowns
// render as SYSTEM date text — iOS keeps them current forever with zero
// widget refreshes (the same mechanism Apple's own clock widgets use).
function overlayCellSize(el) {
  if (el.kind === "clock" || el.kind === "countdown") {
    const s = Math.min(Math.max(Number(el.size) || 34, 8), 90);
    return [s * 0.56 * (el.kind === "clock" ? 7 : 8), s * 1.25];
  }
  const pt = Math.min(Math.max(Number(el.size) || 40, 16), 120);
  return [pt, pt];
}
async function addFreestyleApps(w, design, family, live) {
  const OVERLAY = { app: 1, sleeperlogo: 1, clock: 1, countdown: 1 };
  let apps = (design.canvasElements || []).filter(function (el) { return OVERLAY[el.kind]; });
  // Native texts can't stack on each other — drop shadow-twin clocks and
  // countdowns, keeping only the topmost at a given position.
  apps = apps.filter(function (el, i) {
    if (el.kind !== "clock" && el.kind !== "countdown") return true;
    for (let j = i + 1; j < apps.length; j++) {
      const o = apps[j];
      if (o.kind === el.kind && Math.abs(o.x - el.x) < 0.03 && Math.abs(o.y - el.y) < 0.03) return false;
    }
    return true;
  });
  if (apps.length === 0) return;
  const dims = widgetPointSizes(family);
  const W = dims[0], H = dims[1];
  const tappable = apps.find(function (e) { return e.url; });
  if (!w.url && tappable) w.url = tappable.url;
  // Group into rows: elements whose vertical centers overlap share a row.
  const sorted = apps.slice().sort(function (a, b) { return a.y - b.y; });
  const rows = [];
  for (const el of sorted) {
    const cellH = overlayCellSize(el)[1];
    const top = el.y * H - cellH / 2;
    const last = rows[rows.length - 1];
    if (last && top < last.bottom) {
      last.items.push(el);
      last.bottom = Math.max(last.bottom, top + cellH + (el.showLabel ? 13 : 0));
    } else {
      rows.push({ top: Math.max(0, top), bottom: top + cellH + (el.showLabel ? 13 : 0), items: [el] });
    }
  }
  const root = w.addStack();
  root.layoutVertically();
  root.size = new Size(W, H);
  let cursorY = 0;
  for (const row of rows) {
    if (row.top > cursorY) root.addSpacer(row.top - cursorY);
    const rowStack = root.addStack();
    rowStack.layoutHorizontally();
    rowStack.topAlignContent();
    let cursorX = 0;
    row.items.sort(function (a, b) { return a.x - b.x; });
    for (const el of row.items) {
      const cellDims = overlayCellSize(el);
      const pt = cellDims[0];
      const left = Math.max(0, el.x * W - pt / 2);
      if (left > cursorX) rowStack.addSpacer(left - cursorX);
      if (el.kind === "clock" || el.kind === "countdown") {
        const liveCell = rowStack.addStack();
        liveCell.size = new Size(cellDims[0], cellDims[1]);
        liveCell.centerAlignContent();
        const fs = Math.min(Math.max(Number(el.size) || 34, 8), 90);
        const t = el.kind === "clock"
          ? liveCell.addDate(new Date())
          : liveCell.addDate(new Date((el.dateISO || "2030-01-01") + "T00:00:00"));
        if (el.kind === "clock") { t.applyTimeStyle(); } else { t.applyRelativeStyle(); }
        t.font = fontFor(el.font || design.fontStyle, fs, el.bold !== false);
        t.textColor = new Color(el.colorHex || "#FFFFFF", typeof el.opacity === "number" ? el.opacity : 1);
        t.centerAlignText();
        t.lineLimit = 1;
        t.minimumScaleFactor = 0.4;
        cursorX = left + pt;
        continue;
      }
      const cell = rowStack.addStack();
      cell.layoutVertically();
      if (el.url) cell.url = el.url;
      const iconStack = cell.addStack();
      if (el.kind === "sleeperlogo") {
        // Live Sleeper team avatar as a circular badge; taps open Sleeper.
        const s = live && live.sleeper ? live.sleeper[el.leagueID] : null;
        const team = s ? (el.side === "opp" ? s.oppTeam : s.myTeam) : null;
        let avatar = null;
        if (team && team.avatar) avatar = await loadIcon(team.avatar);
        if (avatar) {
          const img = iconStack.addImage(avatar);
          img.imageSize = new Size(pt, pt);
          img.cornerRadius = pt / 2;
        } else {
          const t = iconStack.addText(el.side === "opp" ? "🛡" : "🏈");
          t.font = Font.systemFont(Math.round(pt * 0.85));
        }
        if (!cell.url) cell.url = "sleeper://";
        cursorX = left + pt;
        continue;
      }
      const elTheme = el.iconTheme && ICON_THEMES[el.iconTheme] ? el.iconTheme : "real";
      let realIcon = null;
      if (elTheme !== "real") {
        const tile = iconStack.addImage(themedIconTile(el, elTheme, apps.indexOf(el), pt));
        tile.imageSize = new Size(pt, pt);
      } else {
        // Custom pack icons travel baked into the script itself.
        if (el.iconB64) { try { realIcon = Image.fromData(Data.fromBase64String(el.iconB64)); } catch (e) {} }
        if (!realIcon && el.iconUrl) realIcon = await loadIcon(el.iconUrl);
        if (realIcon) {
          const img = iconStack.addImage(realIcon);
          img.imageSize = new Size(pt, pt);
          img.cornerRadius = el.shape === "circle" ? pt / 2 : Math.round(pt * 0.24);
        } else {
          const t = iconStack.addText(el.emoji || "📲");
          t.font = Font.systemFont(Math.round(pt * 0.9));
        }
      }
      if (el.showLabel) {
        const labelStack = cell.addStack();
        labelStack.layoutHorizontally();
        labelStack.addSpacer();
        const label = labelStack.addText(el.label || "App");
        label.font = fontFor(design.fontStyle, 9, false);
        label.textColor = new Color(design.textColorHex || "#FFFFFF");
        label.textOpacity = 0.85;
        label.lineLimit = 1;
        labelStack.addSpacer();
      }
      cursorX = left + pt;
    }
    rowStack.addSpacer();
    cursorY = row.bottom;
  }
  root.addSpacer();
}
function hashString(s) {
  let h = 5381;
  for (let i = 0; i < s.length; i++) { h = ((h << 5) + h + s.charCodeAt(i)) >>> 0; }
  return h.toString(36);
}
