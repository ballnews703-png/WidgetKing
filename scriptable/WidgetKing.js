function fontFor(style, size, bold) {
  const names = FONT_NAMES[style];
  if (names) {
    try { return new Font(bold ? names[1] : names[0], size); } catch (e) {}
  }
  if (style === "mono") return bold ? Font.boldMonospacedSystemFont(size) : Font.regularMonospacedSystemFont(size);
  if (style === "classic") return bold ? Font.boldSystemFont(size) : Font.systemFont(size);
  return bold ? Font.boldRoundedSystemFont(size) : Font.regularRoundedSystemFont(size);
}
function themeColors(d) {
  if (d.themeID === "custom" && d.customColors && d.customColors.length === 2) return d.customColors;
  return THEMES[d.themeID] || THEMES.midnight;
}
function daysUntil(iso) {
  if (!iso) return 0;
  const p = iso.split("-").map(Number);
  const target = new Date(p[0], (p[1] || 1) - 1, p[2] || 1);
  const now = new Date();
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  return Math.round((target - today) / 86400000);
}
function centeredText(w, str, font, color) {
  const t = w.addText(str);
  t.font = font; t.textColor = color; t.centerAlignText(); t.minimumScaleFactor = 0.5;
  return t;
}
function hexToRgb(hex) {
  const c = hex.replace("#", "");
  return [parseInt(c.substring(0,2),16), parseInt(c.substring(2,4),16), parseInt(c.substring(4,6),16)];
}
function rgbToHex(rgb) {
  return "#" + rgb.map(function (v) {
    return Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0");
  }).join("");
}

